function ensureDataFiles() {
  if (!fs.existsSync(DATA_DIR)) {
    fs.mkdirSync(DATA_DIR, { recursive: true });
  }
  if (!fs.existsSync(LINKS_FILE)) {
    fs.writeFileSync(LINKS_FILE, JSON.stringify(DEFAULT_LINKS, null, 2), 'utf-8');
  }
  if (!fs.existsSync(PRODUCTS_FILE)) {
    fs.writeFileSync(PRODUCTS_FILE, JSON.stringify(DEFAULT_PRODUCTS, null, 2), 'utf-8');
  }
}

export function getLinkConfigs(): LinkConfig[] {
  try {
    ensureDataFiles();
    const data = fs.readFileSync(LINKS_FILE, 'utf-8');
    return JSON.parse(data) as LinkConfig[];
  } catch (error) {
    console.error('Failed to read links.json:', error);
    return DEFAULT_LINKS;
  }
}

export function saveLinkConfig(config: LinkConfig): boolean {
  try {
    ensureDataFiles();
    const configs = getLinkConfigs();
    const index = configs.findIndex(c => c.id === config.id);
    
    if (index !== -1) {
      configs[index] = { ...configs[index], ...config };
    } else {
      configs.push(config);
    }
    
    fs.writeFileSync(LINKS_FILE, JSON.stringify(configs, null, 2), 'utf-8');
    return true;
  } catch (error) {
    console.error('Failed to save link config:', error);
    return false;
  }
}

export function deleteLinkConfig(id: string): boolean {
  try {
    ensureDataFiles();
    const configs = getLinkConfigs();
    const filtered = configs.filter(c => c.id !== id);
    
    fs.writeFileSync(LINKS_FILE, JSON.stringify(filtered, null, 2), 'utf-8');
    return true;
  } catch (error) {
    console.error('Failed to delete link config:', error);
    return false;
  }
}

